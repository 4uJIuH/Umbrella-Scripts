    if d >= 8 then
        t.k, t.ans = "type", { tostring(count) }
    else
        t.k, t.opts = "choice", variants(tostring(count), { tostring(secs), tostring(count + 1), tostring(count - 1), tostring(secs * 30) })
    end
    if gap == 0.25 then
        t.why = ("Тик длится 1/30 сек, и 0.25 сек не делится на тики нацело: между приказами проходит 8 тиков. Ответ %d."):format(count)
    elseif gap > 0 then
        t.why = ("Приказ в 0, потом каждые %s сек, пока время меньше %d. Ответ %d."):format(tostring(gap), secs, count)
    else
        t.why = ("Без ограничения приказ уходит каждый тик: 30 * %d = %d. Так юнит и дёргается."):format(secs, count)
    end
    return t
end)

