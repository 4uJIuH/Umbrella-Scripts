G("throttle", 11, 6, 9, function(r, d)
    local secs = r:int(2, 5)
    local gap
    if d <= 6 then
        gap = 0
    elseif d <= 8 then
        gap = r:pick({ 0.5, 1 })
    else
        gap = 0.25
    end
    local lines = { "local last = -100", "function script.OnUpdate()", "    local now = GameRules.GetGameTime()" }
    if gap > 0 then
        lines[#lines + 1] = ("    if now - last < %s then return end"):format(tostring(gap))
        lines[#lines + 1] = "    last = now"
    end
    lines[#lines + 1] = "    NPC.MoveTo(hero, target)"
    lines[#lines + 1] = "end"
    local count, last = 0, -100
    for tick = 0, secs * 30 - 1 do
        local now = tick / 30
        if gap == 0 or now - last >= gap then
            last = now
            count = count + 1
        end
    end
    local t = { q = ("OnUpdate вызывается 30 раз в секунду, игровое время идёт от 0. Сколько приказов уйдёт за первые %d сек?"):format(secs),
