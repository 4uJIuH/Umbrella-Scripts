local function variants(right, pool, n)
    local out, seen = { right }, { [right] = true }
    for _, v in ipairs(pool) do
        if #out >= (n or 4) then break end
        if v ~= nil and not seen[v] then
            seen[v] = true
            out[#out + 1] = v
        end
    end
    return out
end

local function near_numbers(v, r)
    local s = tostring(v)
    local pool = {}
    if math.type(v) == "float" then
        if v == math.floor(v) then pool[#pool + 1] = tostring(math.tointeger(v)) end
        pool[#pool + 1] = tostring(math.floor(v))
        pool[#pool + 1] = tostring(v + 1)
    else
        pool[#pool + 1] = tostring(v + 0.0)
    end
    local d = { 1, -1, 2, -2, 3, 10 }
    r:shuffle(d)
    for _, k in ipairs(d) do pool[#pool + 1] = tostring(v + k) end
    pool[#pool + 1] = "ошибка"
    return variants(s, pool)
end

