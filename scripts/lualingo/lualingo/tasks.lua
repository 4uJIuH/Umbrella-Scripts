local function copy(v)
    if type(v) ~= "table" then return v end
    local o = {}
    for k, x in pairs(v) do o[k] = copy(x) end
    return o
end

-- собрать экземпляр задания по id: перемешать варианты, плитки, строки

function B.get(id)
    local t
    local gname, gd, gseed = id:match("^g:([%w_]+):(%d+):(%d+)$")
    if gname then
        local g = gens[gname]
        if not g then return nil end
        local ok, res = pcall(g.make, B.rng(tonumber(gseed)), tonumber(gd))
        if not ok or type(res) ~= "table" then return nil end
        t = res
        t.u, t.d, t.gen = g.u, tonumber(gd), gname
    else
        local src = by_id[id]
        if not src then return nil end
        t = copy(src)
    end
    t.id = id
    local r = B.rng(B.hash(id) + 77)
    if t.k == "choice" then
        local idx = {}
        for i = 1, #t.opts do idx[i] = i end
        r:shuffle(idx)
        local opts = {}
        for i, j in ipairs(idx) do
            opts[i] = t.opts[j]
            if j == 1 then t.ok = i end
        end
        t.right = t.opts[1]
        t.opts = opts
    elseif t.k == "tiles" then
        local bank = {}
        for _, s in ipairs(t.ans) do bank[#bank + 1] = s end
        for _, s in ipairs(t.extra or {}) do bank[#bank + 1] = s end
        r:shuffle(bank)
        t.bank = bank
        t.right = table.concat(t.ans, " ")
    elseif t.k == "order" then
        local bank = {}
        for i = 1, #t.lines do bank[i] = t.lines[i] end
        for _ = 1, 8 do
            r:shuffle(bank)
            local same = true
            for i = 1, #bank do if bank[i] ~= t.lines[i] then same = false break end end
            if not same then break end
        end
        t.bank = bank
    elseif t.k == "match" then
        local right = {}
        for i, p in ipairs(t.pairs) do right[i] = { p[2], i } end
        r:shuffle(right)
        t.rcol = right
    elseif t.k == "type" then
        t.right = t.ans[1]
    end
    return t
end

return B

