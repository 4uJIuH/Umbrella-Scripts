    local n = #w
    local expr, v
    if d <= 5 then
        local i = r:int(1, n - 2)
        local j = r:int(i + 1, n)
        expr = ("(%q):sub(%d, %d)"):format(w, i, j)
        v = w:sub(i, j)
    elseif d == 6 then
        local k = r:int(2, n - 1)
        if r:int(1, 2) == 1 then
            expr = ("(%q):sub(-%d)"):format(w, k)
            v = w:sub(-k)
        else
            expr = ("(%q):sub(%d)"):format(w, k)
            v = w:sub(k)
        end
    elseif d == 7 then
        local a = r:int(3, n)
        local b = r:int(1, a - 1)
        expr = ("(%q):upper():sub(-%d, -%d)"):format(w, a, b)
        v = w:upper():sub(-a, -b)
    else
        local p = r:int(1, n)
        local ch = w:sub(p, p)
        expr = ("select(2, (%q):gsub(%q, \"\"))"):format(w, ch)
        local _, c = w:gsub(ch, "")
        v = c
    end
    local right = tostring(v)
    local pool = {}
    if type(v) == "string" then
        pool = { w:sub(1, #v), w:sub(-#v), right:sub(2) .. w:sub(1, 1), right:lower(), right:upper(), w }
    else
        pool = { tostring(v + 1), tostring(v - 1), tostring(n), "0" }
    end
    local opts = variants(right, pool)
    for i, o in ipairs(opts) do if o == "" then opts[i] = "(пустая строка)" end end
    return { k = "choice", q = "Что выведет код?", code = "print(" .. expr .. ")", out = right ~= "", opts = opts,
        why = "sub(i, j) включает оба края, отрицательные индексы считаются с конца. gsub вторым значением отдаёт число замен." }
end)

G("bits", 12, 7, 10, function(r, d)
    local a, b = r:int(1, 15), r:int(1, 15)
    local forms
    if d <= 7 then
        forms = {
            { "%d & %d", function(x, y) return x & y end },
            { "%d | %d", function(x, y) return x | y end },
        }
    elseif d == 8 then
        forms = {
            { "%d ~ %d", function(x, y) return x ~ y end },
            { "%d << %d", function(x, y) return x << (y % 5) end, true },
            { "%d >> 1 | %d", function(x, y) return x >> 1 | y end },
        }
    else
        forms = {
            { "%d & %d ~= 0", function(x, y) return x & y ~= 0 end },
            { "%d | %d == %d", function(x, y) return x | y == x end, "xx" },
            { "%d ~ %d & 7", function(x, y) return x ~ y & 7 end },
        }
    end
    local f = r:pick(forms)
    local expr
    if f[3] == true then
        expr = f[1]:format(a, b % 5)
    elseif f[3] == "xx" then
        expr = f[1]:format(a, b, a)
    else
        expr = f[1]:format(a, b)
    end
    local v = f[2](a, b)
    local right = tostring(v)
    local opts
    if type(v) == "boolean" then
        opts = variants(right, { tostring(not v), "ошибка", tostring(a & b) })
    else
        opts = near_numbers(v, r)
    end
    local t = { q = "Что выведет код?", code = "print(" .. expr .. ")", out = true, k = "choice", opts = opts }
    if d >= 10 and type(v) ~= "boolean" then
        t.k, t.ans, t.opts, t.q = "type", { right }, nil, "Что выведет код? Впиши ответ."
    end
    t.why = ("%d = %s, %d = %s в двоичной. Порядок: сдвиги сильнее &, & сильнее ~, ~ сильнее |, а сравнения слабее всех."):format(
        a, B.bin(a), b, B.bin(b))
    return t
end)

