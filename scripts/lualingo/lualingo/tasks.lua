-- случайность с зерном, чтобы урок собирался одинаково после перезапуска

local MASK = 0x7fffffff

function B.rng(seed)
    local r = { s = (math.tointeger(seed) or 1) & 0xffffffffffff }
    if r.s == 0 then r.s = 0x5eed end
    function r:next()
        self.s = (self.s * 6364136223846793005 + 1442695040888963407)
        return (self.s >> 33) & MASK
    end
    function r:int(a, b) return a + self:next() % (b - a + 1) end
    function r:float() return self:next() / MASK end
    function r:pick(t) return t[self:int(1, #t)] end
    function r:shuffle(t)
        for i = #t, 2, -1 do
            local j = self:int(1, i)
            t[i], t[j] = t[j], t[i]
        end
        return t
    end
    return r
end

function B.hash(s)
    local h = 5381
    for i = 1, #s do h = (h * 33 + s:byte(i)) & 0xffffffff end
    return h
end

