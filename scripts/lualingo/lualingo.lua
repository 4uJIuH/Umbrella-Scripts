-- московское время

local clock = { delta = nil, last_sync = -1e9, last_try = -1e9, busy = false, sent = 0, src = 1, err = nil }

local function civil_days(y, m, d)
    if m <= 2 then y = y - 1 end
    local era = (y >= 0 and y or y - 399) // 400
    local yoe = y - era * 400
    local doy = (153 * ((m + 9) % 12) + 2) // 5 + d - 1
    local doe = yoe * 365 + yoe // 4 - yoe // 100 + doy
    return era * 146097 + doe - 719468
end

local function parse_time(src, body)
    if src == 1 then
        local ms = body:match('"time"%s*:%s*(%d+)')
        local off = body:match('"offset"%s*:%s*(%-?%d+)')
        if not ms then return nil end
        return tonumber(ms) // 1000 + (tonumber(off) or 10800000) // 1000
    end
    local y = body:match('"year"%s*:%s*(%d+)')
    local mo = body:match('"month"%s*:%s*(%d+)')
    local d = body:match('"day"%s*:%s*(%d+)')
    local h = body:match('"hour"%s*:%s*(%d+)')
    local mi = body:match('"minute"%s*:%s*(%d+)')
    local s = body:match('"seconds"%s*:%s*(%d+)')
    if not (y and mo and d and h and mi and s) then return nil end
    return civil_days(tonumber(y), tonumber(mo), tonumber(d)) * 86400 + tonumber(h) * 3600 + tonumber(mi) * 60 + tonumber(s)
end

local function msk_now()
    if clock.delta == nil then return nil end
    return os.time() + clock.delta
end

local function today()
    local t = msk_now()
    return t and t // 86400 or nil
end

local on_synced

local function on_time(src, res)
    clock.busy = false
    local body = type(res) == "table" and res.response or nil
    local v = type(body) == "string" and parse_time(src, body) or nil
    if not v then
        clock.src = src % #TIME_URLS + 1
        clock.err = "сервер времени не ответил"
        clock.last_try = os.time() - K.sync_retry + 2
        return
    end
    clock.delta = v - os.time()
    clock.last_sync = os.time()
    clock.err = nil
    on_synced()
end

local function sync(force)
    local now = os.time()
    if clock.busy then
        if now - clock.sent < K.sync_timeout then return end
        clock.busy = false
        clock.src = clock.src % #TIME_URLS + 1
        clock.err = "сервер времени молчит"
    end
    if not force then
        if clock.delta and now - clock.last_sync < K.sync_every then return end
        if now - clock.last_try < K.sync_retry then return end
    end
    clock.busy, clock.sent, clock.last_try = true, now, now
    local src = clock.src
    local ok, sent = pcall(HTTP.Request, "GET", TIME_URLS[src], { timeout = 5000 }, function(res) on_time(src, res) end, "lualingo_time")
    if not ok or sent == false then
        clock.busy = false
        clock.err = "HTTP недоступен"
    end
end

