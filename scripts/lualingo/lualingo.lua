local function handle_keys()
    local B = Enum.ButtonCode
    local keys = inp.keys
    inp.keys = {}
    for _, entry in ipairs(keys) do
        local key, shifted = entry[1], entry[2]
        if key == B.KEY_ESCAPE then
            if view.confirm then
                view.confirm = nil
            elseif view.screen == "lesson" then
                view.screen, lesson = "home", nil
            elseif view.screen == "result" then
                view.screen, lesson = "home", nil
            else
                view.open = false
            end
        elseif view.screen == "lesson" and lesson then
            local t, tu = lesson.task, lesson.tui
            local typing = t.k == "type" and lesson.phase == "answer"
            if key == B.KEY_ENTER or key == B.KEY_PAD_ENTER then
                primary()
            elseif typing and key == B.KEY_BACKSPACE then
                tu.text = tu.text:sub(1, -2)
            elseif typing and CHARS[key] then
                if #tu.text < 40 then tu.text = tu.text .. CHARS[key][shifted and 2 or 1] end
            elseif lesson.phase == "answer" and (t.k == "choice" or t.k == "bug") then
                for n = 1, 9 do
                    if key == B["KEY_" .. n] or key == B["KEY_PAD_" .. n] then
                        if t.k == "choice" and t.opts[n] then tu.sel = n end
                        if t.k == "bug" and n <= #code_lines(t.code) then tu.sel = n end
                    end
                end
            end
        elseif view.screen == "result" and (key == B.KEY_ENTER or key == B.KEY_PAD_ENTER) then
            view.screen, lesson = "home", nil
        elseif view.screen == "home" and not view.confirm and (key == B.KEY_ENTER or key == B.KEY_PAD_ENTER) then
            if done_today() then start_lesson("practice") elseif not st.pending then start_lesson("daily") end
        end
    end
end

local function draw_panel()
    load_fonts()
    local ss = Render.ScreenSize()
    local user = ui.scale and ui.scale:Get() / 100 or 1
    D.sc = math.min(ss.x / (K.W + 80), ss.y / (K.H + 60)) * user
    D.sc = clamp(D.sc, 0.45, 2.5)
    D.ox = math.floor((ss.x - K.W * D.sc) / 2)
    D.oy = math.floor((ss.y - K.H * D.sc) / 2)

    Render.FilledRect(Vec2(0, 0), Vec2(ss.x, ss.y), C.dim)
    Render.Shadow(P(0, 0), P(K.W, K.H), Color(0, 0, 0, 200), 40 * D.sc, 18 * D.sc)
    box(0, 0, K.W, K.H, C.bg, 18)

    local cx, cy = Input.GetCursorPos()
    inp.mx, inp.my = ((cx or -1) - D.ox) / D.sc, ((cy or -1) - D.oy) / D.sc

    handle_keys()
    if not view.open then return end

    if view.screen == "intro" then draw_intro()
    elseif view.screen == "lesson" and lesson then draw_lesson()
    elseif view.screen == "result" and lesson then draw_result()
    else
        view.screen = "home"
        draw_home()
        if view.confirm then draw_confirm() end
    end
end

local function draw_reminder()
    local mode = ui.remind and ui.remind:Get() or 0
    if mode == 0 then return end
    if mode == 1 and Engine.IsInGame() then return end
    local t = msk_now()
    if not t or done_today() then return end
    load_fonts()
    D.sc, D.ox, D.oy = 1, 0, 0
    local ss = Render.ScreenSize()
    local streak = streak_now()
    local left = 86400 - t % 86400
    local msg = streak > 0
        and ("Стрик %d сгорит через %dч %02dм: пройди урок дня в Lualingo"):format(streak, left // 3600, left % 3600 // 60)
        or "Lualingo: урок дня ждёт, 10 заданий"
    local w = tsize(F.bold, 15, msg) + 64
    local x, y = math.floor(ss.x / 2 - w / 2), 14
    box(x, y, w, 40, Color(19, 31, 36, 230), 20)
    frame(x, y, w, 40, streak > 0 and C.orange or C.green, 20, 2)
    flame(x + 26, y + 20, 14, streak > 0)
    text(F.bold, 15, msg, x + 46, y + 10, C.text)
end

