local function flow(items, font, size, x, y, maxw, h, gap)
    local out, cx, cy = {}, x, y
    for i, s in ipairs(items) do
        local w = tsize(font, size, s) + 30
        if cx > x and cx + w > x + maxw then
            cx = x
            cy = cy + h + gap
        end
        out[i] = { cx, cy, w }
        cx = cx + w + gap
    end
    return out, cy + h - y
end

local function tile(x, y, w, h, s, state)
    local fill, lip, col = C.card, C.line, C.text
    if state == "ghost" then
        box(x, y, w, h, C.card2, 12)
        return false
    elseif state == "hover" then
        fill, lip = C.blue_bg, C.blue_d
    end
    box(x, y + 3, w, h - 3, lip, 12)
    box(x, y, w, h - 3, fill, 12)
    local _, th = tsize(F.mono, 17, s)
    text(F.mono, 17, s, x + 15, y + (h - 3) / 2 - th / 2, col)
end

local function draw_choice(t, tu, y, x, w)
