local tok_cache = {}

local function tokens(src)
    local hit_ = tok_cache[src]
    if hit_ then return hit_ end
    local out = {}
    local i, n = 1, #src
    local function push(s, col) out[#out + 1] = { s, col } end
    while i <= n do
        local c = src:sub(i, i)
        if src:sub(i, i + 1) == "--" then
            push(src:sub(i), C.com)
            break
        elseif c == '"' or c == "'" then
            local j = i + 1
            while j <= n do
                local d = src:sub(j, j)
                if d == "\\" then j = j + 1 elseif d == c then break end
                j = j + 1
            end
            push(src:sub(i, j), C.str)
            i = j + 1
        elseif src:sub(i, i + 1) == "[[" then
            local j = src:find("]]", i + 2, true) or n - 1
            push(src:sub(i, j + 1), C.str)
            i = j + 2
        elseif c:match("%d") then
            local s = src:match("^0[xX]%x+", i) or src:match("^%d+%.?%d*", i)
            push(s, C.num)
            i = i + #s
        elseif c:match("[%a_]") then
            local s = src:match("^[%w_]+", i)
            local col = C.text
            if s:match("^_+$") and #s >= 3 then col = C.hole
            elseif KW[s] then col = C.kw
            elseif API[s] then col = C.api
            elseif src:sub(i + #s, i + #s) == "(" then col = C.fn end
            push(s, col)
            i = i + #s
        elseif c:match("%s") then
            local s = src:match("^%s+", i)
            push(s, C.text)
            i = i + #s
        else
            local s = src:match("^[%z\1-\127\194-\244][\128-\191]*", i) or c
            push(s, C.sub)
            i = i + #s
        end
    end
    tok_cache[src] = out
    return out
end

local function code_line(src, x, y, size)
    local cx = x
    for _, t in ipairs(tokens(src)) do
        if not t[1]:match("^%s+$") then text(F.mono, size, t[1], cx, y, t[2]) end
        cx = cx + tsize(F.mono, size, t[1])
    end
    return cx - x
end

local function code_lines(code)
    local out = {}
    for l in (code .. "\n"):gmatch("([^\n]*)\n") do out[#out + 1] = l end
    return out
end

local CODE_SIZE, CODE_LH = 17, 25

local function code_block(code, x, y, w, rows)
    local lines = code_lines(code)
    local h = #lines * CODE_LH + 22
    box(x, y, w, h, C.dark, 12)
    for i, l in ipairs(lines) do
        local ly = y + 11 + (i - 1) * CODE_LH
        if rows then rows(i, x, ly - 2, w, CODE_LH) end
        text_r(F.mono, 14, tostring(i), x + 30, ly + 2, C.gray)
        code_line(l, x + 44, ly, CODE_SIZE)
    end
    return h
end

