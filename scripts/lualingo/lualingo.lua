local st = {}

local function rd(fn, key, def)
    local ok, v = pcall(fn, CFG, key, def)
    if ok and v ~= nil then return v end
    return def
end

local function wr(fn, key, v)
    pcall(fn, CFG, key, v)
end

local function split(s, sep)
    local out = {}
    for part in (s or ""):gmatch("[^" .. sep .. "]+") do out[#out + 1] = part end
    return out
end

local function load_state()
    st.placed = rd(Config.ReadInt, "placed", 0) == 1
    st.skill = rd(Config.ReadFloat, "skill", 1.0)
    st.answers = rd(Config.ReadInt, "answers", 0)
    st.xp = rd(Config.ReadInt, "xp", 0)
    st.streak = rd(Config.ReadInt, "streak", 0)
    st.best = rd(Config.ReadInt, "best", 0)
    st.last_day = rd(Config.ReadInt, "last_day", -1)
    st.freezes = rd(Config.ReadInt, "freezes", 0)
    st.pending = rd(Config.ReadInt, "pending", 0) == 1
    st.lessons = rd(Config.ReadInt, "lessons", 0)

    st.days, st.frozen = {}, {}
    for _, d in ipairs(split(rd(Config.ReadString, "days", ""), ",")) do st.days[tonumber(d)] = true end
    for _, d in ipairs(split(rd(Config.ReadString, "frozen", ""), ",")) do st.frozen[tonumber(d)] = true end

    st.seen = split(rd(Config.ReadString, "seen", ""), ",")

    st.stats = {}
    local raw = split(rd(Config.ReadString, "stats", ""), ",")
    for u = 1, #bank.units do
        local ok, n = (raw[u] or "0/0"):match("(%d+)/(%d+)")
        st.stats[u] = { ok = tonumber(ok) or 0, n = tonumber(n) or 0 }
    end

    st.pack = {
        day = rd(Config.ReadInt, "pack_day", -1),
        ids = split(rd(Config.ReadString, "pack_ids", ""), "|"),
        done = rd(Config.ReadString, "pack_done", ""),
        first = rd(Config.ReadString, "pack_first", ""),
        xp = rd(Config.ReadInt, "pack_xp", 0),
    }
end

local function keys_of(set, keep, now)
    local out = {}
    for d in pairs(set) do
        if not now or d > now - keep then out[#out + 1] = d end
    end
    table.sort(out)
    return table.concat(out, ",")
end

local function save_state(today)
    wr(Config.WriteInt, "placed", st.placed and 1 or 0)
    wr(Config.WriteFloat, "skill", st.skill)
    wr(Config.WriteInt, "answers", st.answers)
    wr(Config.WriteInt, "xp", st.xp)
    wr(Config.WriteInt, "streak", st.streak)
    wr(Config.WriteInt, "best", st.best)
    wr(Config.WriteInt, "last_day", st.last_day)
    wr(Config.WriteInt, "freezes", st.freezes)
    wr(Config.WriteInt, "pending", st.pending and 1 or 0)
    wr(Config.WriteInt, "lessons", st.lessons)
    wr(Config.WriteString, "days", keys_of(st.days, K.days_keep, today))
    wr(Config.WriteString, "frozen", keys_of(st.frozen, K.days_keep, today))
    while #st.seen > K.seen_keep do table.remove(st.seen, 1) end
    wr(Config.WriteString, "seen", table.concat(st.seen, ","))
    local s = {}
