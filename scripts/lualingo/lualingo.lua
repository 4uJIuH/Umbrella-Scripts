local function accuracy(u)
    local s = st.stats[u]
    return (s.ok + 1) / (s.n + 2)
end

local function mastery(u)
    return clamp(st.stats[u].ok / K.mastery, 0, 1)
end

local function pick(r, units, target, chosen, kinds, gused)
    local seen = {}
    for _, id in ipairs(st.seen) do seen[id] = true end
    local inunit = {}
    for _, u in ipairs(units) do inunit[u] = true end
    local best, best_score, best_d
    for _, t in ipairs(bank.list) do
        if inunit[t.u] and not chosen[t.id] then
            local sc = math.abs(t.d - target) + (seen[t.id] and 2.5 or 0) + (kinds[t.k] or 0) * 0.6 + r:float() * 0.9
            if not best_score or sc < best_score then best, best_score, best_d = t.id, sc, t.d end
        end
    end
    for _, name in ipairs(bank.gen_order) do
        local g = bank.gens[name]
        if inunit[g.u] then
            local d = clamp(math.floor(target + 0.5), g.dmin, g.dmax)
            local sc = math.abs(d - target) + 0.3 + (gused[name] or 0) * 4 + (seen["g:" .. name] and 1 or 0) + r:float() * 0.9
            if not best_score or sc < best_score then
                best, best_score, best_d = ("g:%s:%d:%d"):format(name, d, r:int(1, 999999)), sc, d
            end
        end
    end
    return best, best_d
end

local function build_pack(seed, count)
    local r = bank.rng(seed)
    local s = st.skill
    local units = unlocked()
    local top = units[#units]
    local weak = {}
    for _, u in ipairs(units) do weak[#weak + 1] = u end
    table.sort(weak, function(a, b) return accuracy(a) < accuracy(b) end)
    local next_unit = bank.units[top + 1] and top + 1 or top
    local wide = {}
    for _, u in ipairs(units) do wide[#wide + 1] = u end
    if next_unit ~= top then wide[#wide + 1] = next_unit end

    local plan = {}
    local fresh = #units == 1 and 10 or 4
    for _ = 1, fresh do plan[#plan + 1] = { { top }, s + r:float() - 0.5 } end
    for _ = 1, 3 do plan[#plan + 1] = { { weak[r:int(1, math.min(2, #weak))] }, s - 0.3 + r:float() * 0.6 } end
    for _ = 1, 2 do plan[#plan + 1] = { { units[r:int(1, #units)] }, s - 0.8 + r:float() } end
    plan[#plan + 1] = { wide, s + 1.2, true }

    local ids, chosen, kinds, gused = {}, {}, {}, {}
    for i = 1, count do
        local p = plan[i] or plan[#plan]
        local id, d = pick(r, p[1], p[2], chosen, kinds, gused)
        if not id then id, d = pick(r, units, s, chosen, kinds, gused) end
        if id then
            chosen[id] = true
            local gname = id:match("^g:([%w_]+):")
            if gname then
                gused[gname] = (gused[gname] or 0) + 1
            else
                local k = bank.by_id[id].k
                kinds[k] = (kinds[k] or 0) + 1
            end
            ids[#ids + 1] = { id = id, d = d, hard = p[3] }
        end
    end
    table.sort(ids, function(a, b)
        if (a.hard or false) ~= (b.hard or false) then return not a.hard end
        return a.d < b.d
    end)
    local out = {}
    for i, x in ipairs(ids) do out[i] = x.id end
    return out
end

