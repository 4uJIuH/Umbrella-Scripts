local function evaluate(t, tu)
    if t.k == "choice" then return tu.sel == t.ok end
    if t.k == "bug" then return tu.sel == t.bad end
    if t.k == "tiles" then
        if #tu.placed ~= #t.ans then return false end
        for i, b in ipairs(tu.placed) do if t.bank[b] ~= t.ans[i] then return false end end
        return true
    end
    if t.k == "order" then
        if #tu.placed ~= #t.lines then return false end
        for i, b in ipairs(tu.placed) do if t.bank[b] ~= t.lines[i] then return false end end
        return true
    end
    if t.k == "type" then
        for _, a in ipairs(t.ans) do if norm(tu.text) == norm(a) then return true end end
        return false
    end
    if t.k == "match" then return tu.mistakes <= 1 end
    return false
end

