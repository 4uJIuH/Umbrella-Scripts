local wrap_cache = {}

local function wrap(font, size, s, maxw)
    local key = font .. ":" .. size .. ":" .. maxw .. ":" .. s .. ":" .. D.sc
    local hit = wrap_cache[key]
    if hit then return hit end
    local out = {}
    for para in (s .. "\n"):gmatch("([^\n]*)\n") do
        local cur = ""
        for word in para:gmatch("%S+") do
            local try = cur == "" and word or (cur .. " " .. word)
            if cur == "" or tsize(font, size, try) <= maxw then
                cur = try
            else
                out[#out + 1] = cur
                cur = word
            end
        end
        out[#out + 1] = cur
    end
    wrap_cache[key] = out
    return out
end

local function paragraph(font, size, s, x, y, maxw, col, lh)
    local lines = wrap(font, size, s, maxw)
    lh = lh or size * 1.35
    for i, l in ipairs(lines) do text(font, size, l, x, y + (i - 1) * lh, col) end
    return #lines * lh
end

