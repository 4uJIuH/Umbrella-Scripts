            local sel = (side == 1 and tu.sl == i) or (side == 2 and tu.sr == i)
            if done then
                fill, edge, col = C.card2, C.card2, C.gray
            elseif tu.flash and ((side == 1 and tu.flash.l == i) or (side == 2 and tu.flash.r == i)) then
                fill, edge = C.red_bg, C.red
            elseif sel then
                fill, edge = C.blue_bg, C.blue
            elseif hov then
                fill = C.card2
            end
            box(cx, ry + 3, cw, rh - 3, edge, 12)
            box(cx, ry, cw, rh - 3, fill, 12)
            text_c(side == 1 and F.mono or F.bold, 16, label, cx + cw / 2, ry + (rh - 3) / 2, col)
            if clk and not done and lesson.phase == "answer" then
                if side == 1 then tu.sl = i else tu.sr = i end
            end
        end
    end
    if tu.sl and tu.sr then
        local l, r = tu.sl, t.rcol[tu.sr][2]
        if l == r then
            tu.matched[l] = true
            snd("ok")
        else
            tu.mistakes = tu.mistakes + 1
            tu.flash = { l = tu.sl, r = tu.sr, t = now }
            snd("bad")
        end
        tu.sl, tu.sr = nil, nil
        local all = true
        for i = 1, #t.pairs do if not tu.matched[i] then all = false end end
        if all then check() end
    end
    return #t.pairs * (rh + 10)
end

local KIND = {
    choice = "Выбери ответ",
    tiles = "Собери из плиток",
    order = "Расставь строки",
    bug = "Найди строку",
    type = "Впиши ответ",
    match = "Найди пары",
}

local function right_answer(t)
    if t.k == "choice" then return t.opts[t.ok] end
    if t.k == "tiles" then return table.concat(t.ans, " ") end
    if t.k == "type" then return t.ans[1] end
    if t.k == "bug" then return "строка " .. t.bad end
    return nil
end

local function primary()
    if not lesson then return end
    if lesson.phase == "answer" then
        if lesson.task.k ~= "match" and can_check() then check() end
    else
        next_task()
    end
end

local function draw_lesson()
    local t, tu = lesson.task, lesson.tui
    local total, solved = #lesson.ids, 0
    for i = 1, total do if lesson.done[i] then solved = solved + 1 end end

    if close_x(30, 30, 20) then
        view.screen = "home"
        lesson = nil
        return
    end
    bar(76, 30, K.W - 200, 20, solved / total, C.green)
    text_r(F.bold, 16, solved .. "/" .. total, K.W - 32, 30, C.sub)
    if lesson.combo >= 3 then
        text_c(F.black, 14, lesson.combo .. " ПОДРЯД!", 76 + (K.W - 200) / 2, 64, C.orange)
    end

    local x, w = 52, K.W - 104
    local unit = bank.units[t.u]
    local chip = ("%s  ·  %s"):format(unit and unit.name or "", KIND[t.k] or "")
    local chw = tsize(F.bold, 13, chip) + 24
    box(x, 84, chw, 26, C.card, 13)
    text(F.bold, 13, chip, x + 12, 88, C.sub)
    for i = 1, 5 do
        dot(x + chw + 16 + (i - 1) * 14, 97, 4, i <= math.ceil(t.d / 2) and C.orange or C.line)
    end
    if lesson.retry then
        text(F.bold, 13, "ПОВТОР ОШИБКИ", x + chw + 96, 89, C.red)
    end

    local y = 124
    y = y + paragraph(F.black, 23, t.q, x, y, w, C.text, 31) + 12

    if t.code and t.k ~= "bug" then
        y = y + code_block(t.code, x, y, w) + 18
    end

    if t.k == "choice" then draw_choice(t, tu, y, x, w)
    elseif t.k == "tiles" then draw_tiles(t, tu, y, x, w)
    elseif t.k == "order" then draw_order(t, tu, y, x, w)
    elseif t.k == "bug" then draw_bug(t, tu, y, x, w)
    elseif t.k == "type" then draw_type(t, tu, y, x, w)
    elseif t.k == "match" then draw_match(t, tu, y, x, w)
    end

    if lesson.phase == "answer" then
        line(0, K.H - 118, K.W, K.H - 118, C.line, 2)
        if t.k ~= "match" then
            if button(32, K.H - 92, 180, 58, "НЕ ЗНАЮ", "gray") then check(true) end
            if button(K.W - 252, K.H - 92, 220, 58, "ПРОВЕРИТЬ", "green", can_check()) then check() end
        else
            text_c(F.bold, 16, "Нажми слева и справа, чтобы соединить пару", K.W / 2, K.H - 62, C.sub)
        end
        return
    end

    local ok = lesson.result
    local why_w = K.W - 64 - 260
    local ans = (not ok) and right_answer(t) or nil
    local why_lines = #wrap(F.reg, 16, t.why or "", why_w)
    local ans_lines = ans and #wrap(F.mono, 17, ans, why_w) or 0
    local bh = math.max(132, 64 + why_lines * 22 + ans_lines * 24 + 20)
    local by = K.H - bh
    box(0, by, K.W, bh, ok and C.green_bg or C.red_bg, 18)
    box(0, by, K.W, 18, ok and C.green_bg or C.red_bg)
    local tx, ty = 40, by + 22
    if ok then
        local cheer = { "Отлично!", "Верно!", "Так держать!", "Супер!", "Чётко!" }
        text(F.black, 24, cheer[(lesson.cur + st.answers) % #cheer + 1], tx, ty, C.green)
    else
        local head = ans and "Правильный ответ:" or "Не совсем"
        if t.k == "order" then head = "Правильный порядок показан выше" end
        if t.k == "match" then head = "Многовато ошибок, пары повторим позже" end
        text(F.black, 24, head, tx, ty, C.red)
    end
    ty = ty + 36
    if ans then
        ty = ty + paragraph(F.mono, 17, ans, tx, ty, why_w, C.text, 24)
    end
    paragraph(F.reg, 16, t.why or "", tx, ty, why_w, ok and Color(190, 230, 170, 255) or Color(255, 200, 200, 255), 22)
    if button(K.W - 252, K.H - 92, 220, 58, "ДАЛЬШЕ", ok and "green" or "red") then next_task() end
end

