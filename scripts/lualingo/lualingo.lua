local function button(x, y, w, h, label, style, enabled, size)
    if enabled == nil then enabled = true end
    local s = STYLE[enabled and style or "off"]
    local hov, clk = hit(x, y, w, h)
    local press = enabled and hov and inp.down
    local lip = 5
    box(x, y + lip, w, h - lip, s[2], 14)
    local top = press and lip - 1 or 0
    box(x, y + top, w, h - lip, s[1], 14)
    if hov and enabled and not press then box(x, y + top, w, h - lip, Color(255, 255, 255, 18), 14) end
    text_c(F.black, size or 18, label, x + w / 2, y + top + (h - lip) / 2, s[3])
    return enabled and clk
end

local function close_x(x, y, sz)
    local hov, clk = hit(x - 6, y - 6, sz + 12, sz + 12)
