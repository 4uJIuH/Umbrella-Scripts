local CHARS = {}

local function build_chars()
    local B = Enum.ButtonCode
    local shifted = ")!@#$%^&*("
    for i = 0, 9 do
        CHARS[B["KEY_" .. i]] = { tostring(i), shifted:sub(i + 1, i + 1) }
        CHARS[B["KEY_PAD_" .. i]] = { tostring(i), tostring(i) }
    end
    for c = string.byte("A"), string.byte("Z") do
        local ch = string.char(c)
        CHARS[B["KEY_" .. ch]] = { ch:lower(), ch }
    end
    local extra = {
        KEY_SPACE = { " ", " " }, KEY_MINUS = { "-", "_" }, KEY_EQUAL = { "=", "+" },
        KEY_LBRACKET = { "[", "{" }, KEY_RBRACKET = { "]", "}" }, KEY_SEMICOLON = { ";", ":" },
