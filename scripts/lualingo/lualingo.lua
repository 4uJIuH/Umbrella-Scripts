    if t.code then
        cols = 2
        for _, o in ipairs(t.opts) do if tsize(F.bold, 17, o) > w / 2 - 80 then cols = 1 end end
    end
    local cw = cols == 2 and (w - 12) / 2 or w
    local ch = 52
    for i, o in ipairs(t.opts) do
        local cx = x + ((i - 1) % cols) * (cw + 12)
