    local t, tu = lesson.task, lesson.tui
    if t.k == "choice" or t.k == "bug" then return tu.sel ~= nil end
    if t.k == "tiles" then return #tu.placed > 0 end
    if t.k == "order" then return #tu.placed == #t.lines end
    if t.k == "type" then return norm(tu.text) ~= "" end
    return false
end

local function remember(id)
    local key = id:match("^(g:[%w_]+):") or id
    for i = #st.seen, 1, -1 do if st.seen[i] == key then table.remove(st.seen, i) end end
    st.seen[#st.seen + 1] = key
end

local function check(forced)
    local t = lesson.task
    local ok = (not forced) and evaluate(t, lesson.tui) or false
    lesson.phase, lesson.result = "checked", ok
    local i = lesson.cur
    if lesson.first[i] == nil then
        lesson.first[i] = ok
        local expect = 1 / (1 + math.exp((t.d - st.skill) * 1.0))
        local k = st.answers < K.k_switch and K.k_new or K.k_old
        st.skill = clamp(st.skill + k * ((ok and 1 or 0) - expect), 1, 10)
        st.answers = st.answers + 1
        local s = st.stats[t.u]
        s.n = s.n + 1
        if ok then s.ok = s.ok + 1 end
        remember(lesson.ids[i])
    end
    if ok then
        lesson.done[i] = true
        local gain = lesson.first[i] and (K.xp_base + math.floor(t.d / 2)) or K.xp_repeat
        lesson.xp = lesson.xp + gain
        st.xp = st.xp + gain
        lesson.combo = lesson.combo + 1
        if lesson.combo > lesson.best_combo then lesson.best_combo = lesson.combo end
        snd("ok")
    else
        lesson.combo = 0
        lesson.tries[i] = (lesson.tries[i] or 0) + 1
        if lesson.tries[i] < K.retries then
            lesson.queue[#lesson.queue + 1] = i
        else
            lesson.done[i] = true
        end
        snd("bad")
    end
    persist_lesson()
end

finish = function()
    local total, good = 0, 0
    for i = 1, #lesson.ids do
        total = total + 1
        if lesson.first[i] then good = good + 1 end
    end
    local bonus = K.xp_finish + (good == total and K.xp_perfect or 0)
    lesson.bonus = bonus
    lesson.xp = lesson.xp + bonus
    st.xp = st.xp + bonus
    st.lessons = st.lessons + 1
    lesson.acc = total > 0 and good / total or 1
    if lesson.mode == "daily" then
        st.pack.xp = lesson.xp
        credit_day()
    else
        save_state(today())
    end
    snd("done")
    view.screen = "result"
    view.anim = os.clock()
end

