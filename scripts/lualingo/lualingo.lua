function script.OnFrame()
    if not st.stats then return end
    view.frame_t = os.clock()
    sync(false)

    if ui.bind and not (view.open and lesson and lesson.task and lesson.task.k == "type") then
        local ok, pressed = pcall(ui.bind.IsPressed, ui.bind)
        if ok and pressed then
            if view.open then view.open = false else open_panel() end
        end
    end

    if not view.open then
        inp.keys = {}
        draw_reminder()
        return
    end

    local raw = inp.ev_down
    if not raw then
        local ok, d = pcall(Input.IsKeyDown, Enum.ButtonCode.KEY_MOUSE1)
        raw = ok and d or false
    end
    inp.clicked = inp.pend or (raw and not inp.prev)
    inp.down = raw
    inp.prev = raw or inp.pend
    inp.pend = false
    if Menu.Opened() then inp.clicked = false end

    draw_panel()
end

function script.OnKeyEvent(data)
    if not view.open or type(data) ~= "table" then return true end
    if os.clock() - view.frame_t > K.grace then return true end
    if Menu.Opened() then return true end
    local B, E = Enum.ButtonCode, Enum.EKeyEvent
    local key, ev = data.key, data.event
    if ev == E.EKeyEvent_KEY_DOWN then
        if key == B.KEY_END then
            view.open = false
            return false
        end
        if key == B.KEY_MOUSE1 then
            inp.pend, inp.ev_down = true, true
        elseif key == B.KEY_LSHIFT or key == B.KEY_RSHIFT then
            inp.shift = true
        else
            inp.keys[#inp.keys + 1] = { key, shift_down() }
        end
    elseif ev == E.EKeyEvent_KEY_UP then
        if key == B.KEY_MOUSE1 then
            inp.ev_down = false
        elseif key == B.KEY_LSHIFT or key == B.KEY_RSHIFT then
            inp.shift = false
        end
    end
    return false
end

return script

