end

local function flame(cx, cy, s, lit)
    local outer = lit and C.orange or C.gray
    local inner = lit and C.yellow or C.gray_d
    dot(cx, cy + s * 0.22, s * 0.5, outer)
    tri(cx - s * 0.49, cy + s * 0.12, cx + s * 0.49, cy + s * 0.12, cx + s * 0.05, cy - s * 0.75, outer)
    tri(cx - s * 0.49, cy + s * 0.12, cx - s * 0.1, cy - s * 0.25, cx - s * 0.42, cy - s * 0.35, outer)
    dot(cx, cy + s * 0.36, s * 0.27, inner)
    tri(cx - s * 0.26, cy + s * 0.3, cx + s * 0.26, cy + s * 0.3, cx + s * 0.02, cy - s * 0.18, inner)
end

local function flake(cx, cy, s, col)
    for a = 0, 2 do
        local ang = a * math.pi / 3
        local dx, dy = math.cos(ang) * s, math.sin(ang) * s
        line(cx - dx, cy - dy, cx + dx, cy + dy, col, 2)
    end
    dot(cx, cy, s * 0.25, col)
end

local function bar(x, y, w, h, frac, col)
    box(x, y, w, h, C.line, h / 2)
    frac = clamp(frac, 0, 1)
    if frac > 0 then
        local fw = math.max(h, w * frac)
        box(x, y, fw, h, col, h / 2)
        box(x + h / 2, y + h * 0.2, math.max(0, fw - h), h * 0.22, Color(255, 255, 255, 50), h * 0.11)
    end
end

local function level_of(xp)
    local l = math.floor((1 + math.sqrt(1 + 4 * xp / 25)) / 2)
    return l, 25 * l * (l - 1), 25 * l * (l + 1)
end

local function card(x, y, w, h)
    box(x, y + 3, w, h, C.line, 16)
    box(x, y, w, h, C.card, 16)
end

