local function credit_day()
    local t = today()
    if not t then
        st.pending = true
        save_state()
        return
    end
    st.pending = false
    if st.last_day >= t then
        save_state(t)
        return
    end
    local gap = st.last_day >= 0 and (t - st.last_day) or math.huge
    local froze = 0
    if gap == 1 then
        st.streak = st.streak + 1
    elseif gap ~= math.huge and gap - 1 <= st.freezes then
        froze = gap - 1
        st.freezes = st.freezes - froze
        for d = st.last_day + 1, t - 1 do st.frozen[d] = true end
        st.streak = st.streak + 1
    else
        st.streak = 1
    end
    st.last_day = t
    st.days[t] = true
    local got = false
    if st.streak % K.freeze_every == 0 and st.freezes < K.freeze_max then
        st.freezes = st.freezes + 1
        got = true
    end
    if st.streak > st.best then st.best = st.streak end
    credit_note = { streak = st.streak, froze = froze, got = got }
    save_state(t)
    snd("streak")
end

