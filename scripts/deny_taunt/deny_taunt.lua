local ui = {}

function script.OnScriptsLoaded()
    local tab = Menu.Create("Scripts", "Utility", "Денай-токсик", "Main")
    local main = tab:Create("Подколы", Enum.GroupSide.Left)

    ui.on = main:Switch("Включить", true, "\u{f0e7}")
    ui.on:ToolTip("После твоего деная противник на линии получает подкол в чат.")

    ui.chat = main:Combo("Куда писать", { "Общий чат", "Только союзникам" }, 0)
    ui.chat:ToolTip("Общий чат видят противники. «Только союзникам» - посмеяться своей командой.")

    ui.cd = main:Slider("Пауза между подколами", 5, 120, COOLDOWN, "%d с")
    ui.cd:ToolTip("Чаще не пишет, даже если денаишь каждого крипа. Иначе дота заглушит чат, а противник замьютит.")

    ui.chance = main:Slider("Шанс подкола", 10, 100, CHANCE, "%d%%")
    ui.chance:ToolTip("Не на каждый денай, чтобы не приедалось.")

    ui.custom = main:Input("Свои фразы", "")
    ui.custom:ToolTip("Через точку с запятой. {hero} заменится на героя противника. Если пусто - встроенные фразы.")
end

-- логика

local lastSaid = -100
local lastText = nil

local function heroName(h)
    local n = (NPC.GetUnitName(h) or ""):gsub("^npc_dota_hero_", ""):gsub("_", " ")
    return (n:gsub("^%l", string.upper))
end

local function laneEnemy(me, pos)
    local best, bestD = nil, NEAR
    for _, h in ipairs(Heroes.GetAll()) do
        if Entity.GetTeamNum(h) ~= Entity.GetTeamNum(me) and Entity.IsAlive(h) and not Entity.IsDormant(h) and not NPC.IsIllusion(h) then
            local d = (Entity.GetAbsOrigin(h) - pos):Length2D()
            if d < bestD then best, bestD = h, d end
        end
    end
    return best
end

local function phrases()
    local out = {}
    for raw in (ui.custom:Get() or ""):gmatch("[^;]+") do
        local p = raw:match("^%s*(.-)%s*$")
        if p ~= "" then out[#out + 1] = p end
    end
    return #out > 0 and out or TAUNTS
end

local function taunt(enemy)
    local list = phrases()
    local text
    for _ = 1, 5 do
        text = list[math.random(#list)]
        if text ~= lastText or #list == 1 then break end
    end
    lastText = text
    text = text:gsub("{hero}", heroName(enemy))
    local channel = ui.chat:Get() == 1 and CH_ALLIES or CH_ALL
    local ok, err = pcall(Chat.Say, channel, text)
    if not ok then print("[денай-токсик] Chat.Say: " .. tostring(err)) end
end

function script.OnEntityKilled(data)
    if not ui.on or not ui.on:Get() or type(data) ~= "table" then return end
    local me = Heroes.GetLocal()
    local creep = data.target
    if not me or data.source ~= me or not creep or Entity.IsHero(creep) then return end
    if Entity.GetTeamNum(creep) ~= Entity.GetTeamNum(me) then return end

    local now = os.clock()
    if now - lastSaid < ui.cd:Get() then return end
    if math.random(100) > ui.chance:Get() then return end

    local enemy = laneEnemy(me, Entity.GetAbsOrigin(creep))
    if not enemy then return end
    lastSaid = now
    taunt(enemy)
end

return script


