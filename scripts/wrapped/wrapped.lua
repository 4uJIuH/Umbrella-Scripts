    return os.clock()
end

local function mmss(s)
    s = math.max(0, math.floor(s))
    return string.format("%d:%02d", s // 60, s % 60)
end

local function short(n)
    if n >= 1000 then return string.format("%.1fk", n / 1000) end
    return tostring(math.floor(n))
end

local function top(t)
    local best, n = nil, 0
    for k, v in pairs(t) do if v > n then best, n = k, v end end
    return best, n
end

local function clean(s) return (tostring(s or ""):gsub("[~^]", "")) end

local function plural(n, one, few, many)
    local a, b = n % 10, n % 100
    if a == 1 and b ~= 11 then return n .. " " .. one end
    if a >= 2 and a <= 4 and (b < 12 or b > 14) then return n .. " " .. few end
    return n .. " " .. many
end

local function capital(s)
    return (s:gsub("^%l", string.upper))
end

local function unitTitle(name)
    if not name then return "?" end
    if SPECIAL[name] then return SPECIAL[name] end
    local loc = try(GameLocalizer and GameLocalizer.FindNPC, name)
    if loc and loc ~= "" then return loc end
    return capital((name:gsub("^npc_dota_hero_", ""):gsub("^npc_dota_", ""):gsub("_", " ")))
end

local function abilityTitle(name)
    local loc = try(GameLocalizer and GameLocalizer.FindAbility, name)
    if loc and loc ~= "" then return loc end
    return capital((name:gsub("_", " ")))
end

local function icon(name)
    if not name or name:sub(1, 1) == "#" then return nil end
    if images[name] == nil then images[name] = try(Render.LoadImage, ICON:format(name)) or false end
    return images[name] or nil
end

