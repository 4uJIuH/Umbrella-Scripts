local function packCard(c)
    local out = { c.hero or "", c.title or "", table.concat(c.kda, ","), tostring(c.length or 0),
        c.challenge or "", table.concat(c.ach, ",") }
    for _, t in ipairs(c.tiles) do out[#out + 1] = t.value .. "^" .. t.text .. "^" .. (t.icon or "") end
    return table.concat(out, "~")
end

local function unpackCard(s)
    if not s or s == "" then return nil end
    local parts = {}
    for p in (s .. "~"):gmatch("(.-)~") do parts[#parts + 1] = p end
    if #parts < 6 then return nil end
    local c = { hero = parts[1], title = parts[2], kda = {}, length = tonumber(parts[4]) or 0, tiles = {}, ach = {} }
    for n in parts[3]:gmatch("[^,]+") do c.kda[#c.kda + 1] = tonumber(n) or 0 end
    if parts[5] ~= "" then c.challenge = parts[5] end
    for n in parts[6]:gmatch("[^,]+") do c.ach[#c.ach + 1] = n end
    for i = 7, #parts do
        local v, t, ic = parts[i]:match("^(.-)%^(.-)%^(.*)$")
        if v then c.tiles[#c.tiles + 1] = { value = v, text = t, icon = ic ~= "" and ic or nil } end
    end
    return c
end

local function finish()
    if not m or m.finished then return end
    snapshot()
    if m.alive then m.longestLife = math.max(m.longestLife, now() - m.lifeStart) end
    m.finished = true

    local id = tostring(m.id)
    if id == "0" or Config.ReadString(CFG, "last_match", "") ~= id then
        local k, d = kda()
        profile.games = profile.games + 1
        profile.kills = profile.kills + k
        profile.deaths = profile.deaths + d
        profile.dist = profile.dist + math.floor(m.distance / 1000)
        if challengeKey() ~= "none" and m.violations == 0 then profile.sgrades = profile.sgrades + 1 end
        for key, v in pairs(profile) do Config.WriteInt(CFG, "p_" .. key, v) end
        Config.WriteString(CFG, "last_match", id)
    end

    checkAch(true)
    card = buildCard()
    Config.WriteString(CFG, "last_card", packCard(card))
    if ui.autoshow and ui.autoshow:Get() then showCard = true end
end

