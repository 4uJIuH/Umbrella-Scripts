-- логика

function script.OnUpdate()
    if not ui.enabled or not ui.enabled:Get() then return end
    local hero = Heroes.GetLocal()
    if not hero then return end

    local id = try(GameRules.GetMatchID) or 0
    if not m or m.id ~= id or m.heroName ~= NPC.GetUnitName(hero) or now() < m.last - 5 then newMatch(hero, id) end

    if ui.showNow:IsPressed() then
        if showCard then showCard = false else card = buildCard(); showCard = true end
    end

    if m.finished then return end

    local chosen = ui.challenge:Get() + 1
    if chosen ~= m.challenge then
        m.challenge, m.violations, m.challengeFrom = chosen, 0, clock()
    end

    track(hero)
end

function script.OnFrame()
    if ui.book and ui.book:IsPressed() then showBook = not showBook end
    if not showCard and not showBook and #toasts == 0 and not (m and ui.hud and ui.hud:Get()) then return end
    if not getFont() then return end

    local mouse = Input.IsKeyDownOnce(Enum.ButtonCode.KEY_MOUSE1, true)
    if m and not m.finished and challengeKey() ~= "none" and ui.hud:Get() and Heroes.GetLocal() then drawHud() end
    if showCard and card then drawCard(card, mouse) end
    if showBook then drawBook(mouse) end
    if #toasts > 0 then drawToasts() end
end

function script.OnPrepareUnitOrders(data)
    if not m or m.finished or type(data) ~= "table" then return true end
    if data.player ~= Players.GetLocal() or type(data.identifier) == "string" then return true end

    local t = now()
    m.orders = m.orders + 1
    m.apm[#m.apm + 1] = t
    while m.apm[1] and t - m.apm[1] > 60 do table.remove(m.apm, 1) end
    m.peakApm = math.max(m.peakApm, #m.apm)

    local k = challengeKey()
    if k == "calm" and #m.apm > 40 and t - m.lastViolation > 60 then violate() end

    if castOrders[data.order] and data.ability then
        local name = try(Ability.GetName, data.ability) or ""
        local item = name:sub(1, 5) == "item_"
        if not item and name ~= "" then
            m.casts = m.casts + 1
            m.castsBy[name] = (m.castsBy[name] or 0) + 1
        end
        if k == "rmb" or (k == "noskills" and not item) then violate() end
    end
    return true
end

function script.OnEntityKilled(data)
    if not m or m.finished or type(data) ~= "table" then return end
    local target = data.target
    if target == m.hero then
        local key = whoKey(data.source)
        m.deathsBy[key] = (m.deathsBy[key] or 0) + 1
        m.deaths = m.deaths + 1
        m.streak = 0
        if challengeKey() == "immortal" then violate() end
        return
    end
    if target and try(Entity.IsHero, target) and not try(NPC.IsIllusion, target)
        and not try(Entity.IsSameTeam, target, m.hero) and realHero(data.source) == m.hero then
        local n = try(NPC.GetUnitName, target)
        if n then m.killsOf[n] = (m.killsOf[n] or 0) + 1 end
        m.kills = m.kills + 1
        m.streak = m.streak + 1
        m.bestStreak = math.max(m.bestStreak, m.streak)
    end
end

function script.OnEntityHurt(data)
    if not m or m.finished or type(data) ~= "table" then return end
    local dmg = num(data.damage)
    if data.target == m.hero then
        local key = whoKey(data.source)
        m.hurtBy[key] = (m.hurtBy[key] or 0) + dmg
        m.taken = m.taken + dmg
        return
    end
    if data.target and try(Entity.IsHero, data.target) and not try(Entity.IsSameTeam, data.target, m.hero)
        and realHero(data.source) == m.hero then
        m.dealt = m.dealt + dmg
        if challengeKey() == "pacifist" and clock() < 600 and now() - m.lastViolation > 3 then violate() end
    end
end

function script.OnGameEnd()
    finish()
end

