        local col = i <= half and 0 or 1
        local row = (i - 1) % half
        local ax = x + pad + col * colW
        local ay = y + pad + 44 + row * rowH
        local on = unlocked[a.id]
        star(ax + 12, ay + 16, 10, on and C.gold or Color(255, 255, 255, 40))
        text(14, a.name, ax + 30, ay + 2, on and C.white or Color(255, 255, 255, 110))
        text(fit(11, a.desc, colW - 40), a.desc, ax + 30, ay + 21, on and C.muted or Color(255, 255, 255, 70))
    end
end

local function drawToasts()
    local screen = Render.ScreenSize()
    local t = real()
    local y = 90
    for i = #toasts, 1, -1 do
        if t - toasts[i].t > 5 then table.remove(toasts, i) end
    end
    for _, toast in ipairs(toasts) do
        local age = t - toast.t
        local slide = math.min(1, age / 0.25)
        local alpha = age > 4.5 and math.max(0, 1 - (age - 4.5) / 0.5) or 1
        local W, H = 310, 62
        local x = screen.x - (W + 24) * slide
        Render.SetGlobalAlpha(alpha)
        Render.Shadow(Vec2(x, y), Vec2(x + W, y + H), C.shadow, 18, 10)
        Render.Gradient(Vec2(x, y), Vec2(x + W, y + H), C.bgTop, C.bgBottom, C.bgTop, C.bgBottom, 10)
        Render.FilledRect(Vec2(x, y), Vec2(x + 4, y + H), C.gold, 2)
        star(x + 30, y + 31, 15, C.gold)
        text(11, "АЧИВКА ОТКРЫТА", x + 54, y + 8, C.gold)
        text(16, toast.a.name, x + 54, y + 22, C.white)
        text(fit(11, toast.a.desc, W - 64), toast.a.desc, x + 54, y + 42, C.muted)
        Render.ResetGlobalAlpha()
        y = y + H + 10
    end
end

local function drawHud()
    local ch = CHALLENGES[m.challenge]
    local screen = Render.ScreenSize()
    local label = "челлендж: " .. ch.name .. "   нарушений: " .. m.violations .. "   сейчас: " .. grade(m.violations)
    local W = width(14, label) + 32
    local x, y = math.floor((screen.x - W) / 2), 64
    local hot = real() - flash < 0.6
    Render.FilledRect(Vec2(x, y), Vec2(x + W, y + 30), hot and Color(160, 30, 40, 220) or Color(20, 18, 40, 200), 15)
    Render.Rect(Vec2(x, y), Vec2(x + W, y + 30), hot and C.red or Color(255, 255, 255, 30), 15, Enum.DrawFlags.None, 1)
    text(14, label, x + 16, y + 7, C.white)
end

