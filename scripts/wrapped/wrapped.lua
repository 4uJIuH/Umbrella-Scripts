local function violate()
    if challengeKey() == "none" then return end
    m.violations = m.violations + 1
    m.lastViolation = now()
    flash = real()
    if ui.sound and ui.sound:Get() then try(Engine.PlayVol, FAIL_SOUND, 0.15) end
