local function snapshot()
    local player = Players.GetLocal()
    local td = try(Player.GetTeamData, player)
    if type(td) == "table" then m.kda = { num(td.kills), num(td.deaths), num(td.assists) } end
    local tp = try(Player.GetTeamPlayer, player)
    if type(tp) == "table" then
        for _, k in ipairs(STAT_KEYS) do m.stats[k] = num(tp[k]) end
    end
    local wards = stat("observer_wards_placed") + stat("sentry_wards_placed")
    if m.wards and wards > m.wards and challengeKey() == "nowards" then
        for _ = 1, wards - m.wards do violate() end
    end
    m.wards = wards
end

local function track(hero)
    local t = now()
    local dt = math.max(0, math.min(1, t - m.last))
    m.last = t

    local alive = Entity.IsAlive(hero)
    if alive then
        if not m.alive then m.lifeStart = t end
        local pos = Entity.GetAbsOrigin(hero)
        local moved = m.pos and pos:Distance2D(m.pos) or 0
        if moved > 1200 then m.jumps = m.jumps + 1
        elseif moved > 2 then m.distance = m.distance + moved end
        m.pos = pos

        local busy = moved > 2 or NPC.IsAttacking(hero) or NPC.IsChannellingAbility(hero) or NPC.IsStunned(hero)
        if busy or clock() <= 0 then
            m.idle, m.still = 0, 0
        else
            m.idle = m.idle + dt
            m.still = m.still + dt
            m.longestIdle = math.max(m.longestIdle, m.idle)
            if challengeKey() == "move" and m.still >= 2 then m.still = 0; violate() end
        end

        local hp, maxHp = Entity.GetHealth(hero), Entity.GetMaxHealth(hero)
        if maxHp > 0 and hp > 0 and hp / maxHp < 0.25 and (not m.low or hp < m.low.hp) then
            m.low = { hp = hp, t = t }
        end
        if m.low and t - m.low.t > 3 then
            if not m.closest or m.low.hp < m.closest then m.closest = math.floor(m.low.hp) end
            m.low = nil
        end
    else
        if m.alive then m.longestLife = math.max(m.longestLife, t - m.lifeStart) end
        m.dead = m.dead + dt
        m.pos, m.low, m.idle, m.still = nil, nil, 0, 0
    end
    m.alive = alive

    if t - m.snap >= 2 then
        m.snap = t
        snapshot()
        checkAch(false)
    end
end

