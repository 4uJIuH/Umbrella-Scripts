-- карта

local function zone(pos)
    if pos.x < -BASE_EDGE and pos.y < -BASE_EDGE then return "radiant_base" end
    if pos.x > BASE_EDGE and pos.y > BASE_EDGE then return "dire_base" end
    local d = pos.y - pos.x
    if d > LANE_SPLIT then return "top" end
    if d < -LANE_SPLIT then return "bot" end
    return "mid"
end

local function shortName(hero)
    local name = NPC.GetUnitName(hero) or ""
    return (name:gsub("^npc_dota_hero_", ""):gsub("_", " "))
end

local function clock(t)
    t = math.max(0, math.floor(t))
    return string.format("%d:%02d", t // 60, t % 60)
end

-- наблюдения

local deaths = {}
local lastSeen = {}

function script.OnEntityKilled(data)
    if type(data) ~= "table" or not data.target then return end
    local me = Heroes.GetLocal()
    local who = data.target
    if not me or not Entity.IsHero(who) or NPC.IsIllusion(who) then return end
    if Entity.GetTeamNum(who) ~= Entity.GetTeamNum(me) then return end
    deaths[#deaths + 1] = { zone = zone(Entity.GetAbsOrigin(who)), t = GameRules.GetDOTATime() }
end

local function watch(me, now)
    for _, h in ipairs(Heroes.GetAll()) do
        if Entity.GetTeamNum(h) ~= Entity.GetTeamNum(me) and not NPC.IsIllusion(h) and Entity.IsAlive(h) and not Entity.IsDormant(h) then
            lastSeen[h] = { zone = zone(Entity.GetAbsOrigin(h)), t = now }
        end
    end
end

