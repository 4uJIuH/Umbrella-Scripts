    for _, h in ipairs(Heroes.GetAll()) do
        if Entity.GetTeamNum(h) ~= Entity.GetTeamNum(me) and not NPC.IsIllusion(h) and Entity.IsAlive(h) then
            if not Entity.IsDormant(h) then
                if zone(Entity.GetAbsOrigin(h)) == lane then visible = visible + 1 end
            else
                local seen = lastSeen[h]
                if seen and seen.zone == lane and now - seen.t < FOG_MEMORY then fog[#fog + 1] = shortName(h) end
            end
        end
    end
    if visible >= 3 then return "шторм, " .. visible .. " врага" end
    if visible == 2 then return "гроза, 2 врага" end
    if visible == 1 then return "облачно, 1 враг" end
    if #fog > 0 then
        if ui.names:Get() then return "туман, пропали " .. table.concat(fog, ", ") end
        return "туман, пропало " .. #fog
    end
    for _, d in ipairs(deaths) do
        if d.zone == lane and now - d.t < DEATH_MEMORY then return "прошли осадки из наших" end
    end
    return "ясно"
end

local function forecast(me)
    local now = GameRules.GetDOTATime()
    local tod = GameRules.GetTimeOfDay() or 0.5
    local night = tod < 0.25 or tod >= 0.75
    local lines = {}

    lines[#lines + 1] = string.format("Прогноз погоды на %s. %s, ветер %s.", clock(now),
        night and "Ночь, видимость низкая" or "День, видимость хорошая", WINDS[math.random(#WINDS)])

    for _, lane in ipairs(LANES) do
        lines[#lines + 1] = lane[2] .. ": " .. weather(lane[1], me, now) .. "."
    end

    local missing = 0
    for _, h in ipairs(Heroes.GetAll()) do
        if Entity.GetTeamNum(h) ~= Entity.GetTeamNum(me) and not NPC.IsIllusion(h) and Entity.IsAlive(h) and Entity.IsDormant(h) then
            missing = missing + 1
        end
    end
    if missing >= 3 then
        lines[#lines + 1] = "Штормовое предупреждение: не видно " .. missing .. " врагов."
    end

    if ui.outro:Get() then lines[#lines + 1] = OUTROS[math.random(#OUTROS)] end
    return lines
end

-- чат

local queue = {}
local nextMsg = 0
local shown = nil
local nextForecast = nil

local function publish(lines)
    if ui.private:Get() then
        shown = { lines = lines, till = os.clock() + SHOW_SECONDS }
        return
    end
    for _, l in ipairs(lines) do queue[#queue + 1] = l end
end

local function drain()
    if not queue[1] or os.clock() < nextMsg then return end
    local ok, err = pcall(Chat.Say, ALLIES, table.remove(queue, 1))
    if not ok then print("[синоптик] Chat.Say: " .. tostring(err)) end
    nextMsg = os.clock() + MSG_GAP
end

function script.OnUpdate()
    if not ui.on or not ui.on:Get() or not Engine.IsInGame() then return end
    local me = Heroes.GetLocal()
    if not me then return end
    local now = GameRules.GetDOTATime()
    watch(me, now)

    while deaths[1] and now - deaths[1].t > DEATH_MEMORY do table.remove(deaths, 1) end

    local due = ui.now:IsPressed()
    if not nextForecast then nextForecast = now + ui.every:Get() * 60 end
    if now >= nextForecast then due = true end
    if due then
        nextForecast = now + ui.every:Get() * 60
        publish(forecast(me))
    end
    drain()
end

-- рисуем

local font = nil

function script.OnDraw()
    if not shown or os.clock() > shown.till then return end
    if not font then font = Render.LoadFont("Tahoma", Enum.FontCreate.FONTFLAG_ANTIALIAS, 500) end
    local y = 140
    for _, l in ipairs(shown.lines) do
        Render.Text(font, 15, l, Vec2(21, y + 1), Color(0, 0, 0, 200))
        Render.Text(font, 15, l, Vec2(20, y), Color(200, 225, 255, 240))
        y = y + 20
    end
end

return script


