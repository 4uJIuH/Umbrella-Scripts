-- счёт

local function meters(units) return units * CM_PER_UNIT / 100 end

local function km(units) return string.format("%.2f км", meters(units) / 1000) end

local function steps(units) return math.floor(meters(units) / STEP_M) end

local function plural(n, many, one, few)
    local d, dd = n % 10, n % 100
    if d == 1 and dd ~= 11 then return one end
    if d >= 2 and d <= 4 and (dd < 12 or dd > 14) then return few end
    return many
end

local function compare(units)
    local m = meters(units)
    for _, t in ipairs(THINGS) do
        local n = m / t[1]
        if n >= 1 then
            local whole = math.floor(n)
            return string.format("Это %d %s", whole, plural(whole, t[2], t[3], t[4]))
        end
    end
    return "Это меньше бассейна. Ты вообще двигался?"
end

local today = os.date("%Y-%m-%d")
local game = { walked = 0, flown = 0 }
local saved = { day = 0, total = 0 }
local hero, last = nil, nil
local lastSave = 0
local goalDone = false
local summary = nil

local function load()
    if Config.ReadString(CFG, "day", "") ~= today then
        Config.WriteString(CFG, "day", today)
        Config.WriteFloat(CFG, "day_units", 0)
        Config.WriteInt(CFG, "goal_done", 0)
    end
    saved.day = Config.ReadFloat(CFG, "day_units", 0)
    saved.total = Config.ReadFloat(CFG, "total_units", 0)
    goalDone = Config.ReadInt(CFG, "goal_done", 0) == 1
end

local function save()
    Config.WriteFloat(CFG, "day_units", saved.day + game.walked)
    Config.WriteFloat(CFG, "total_units", saved.total + game.walked)
    Config.WriteInt(CFG, "goal_done", goalDone and 1 or 0)
    lastSave = os.clock()
end

local function newGame(h)
    if hero then save() end
    load()
    hero, last = h, nil
    game.walked, game.flown = 0, 0
end

local function showSummary()
    local day, total = saved.day + game.walked, saved.total + game.walked
    summary = {
        till = os.clock() + SHOW_SECONDS,
        lines = {
            string.format("За игру: %s, %d шагов, %d ккал", km(game.walked), steps(game.walked), math.floor(meters(game.walked) / 1000 * KCAL_PER_KM)),
            compare(game.walked) .. ".",
            string.format("Телепортами и блинками: %s (не в счёт)", km(game.flown)),
            string.format("Сегодня: %s, %d из %d шагов", km(day), steps(day), ui.goal:Get()),
            string.format("За всё время: %s", km(total)),
        },
    }
end

function script.OnUpdate()
    if not ui.on or not ui.on:Get() then return end
    local h = Heroes.GetLocal()
    if not h then return end
    if h ~= hero then newGame(h) end

    local pos = Entity.GetAbsOrigin(h)
    if Entity.IsAlive(h) and last then
        local d = (pos - last):Length2D()
        if d > JUMP then
            game.flown = game.flown + d
        elseif d > JITTER then
            game.walked = game.walked + d
        end
    end
    last = Entity.IsAlive(h) and pos or nil

    if not goalDone and steps(saved.day + game.walked) >= ui.goal:Get() then
        goalDone = true
        Render.CenteredNotification("Шагомер: цель на день выполнена! " .. ui.goal:Get() .. " шагов", 4)
        save()
    end

    if ui.show:IsPressed() then showSummary() end
    if os.clock() - lastSave > SAVE_EVERY then save() end
end

function script.OnGameEnd()
    if not hero then return end
    save()
    showSummary()
    if ui.brag:Get() then
        local text = string.format("Шагомер: за игру пробежал %s. %s.", km(game.walked), compare(game.walked))
        pcall(Chat.Say, ALLIES, text)
    end
end

-- рисуем

local font = nil

local function text(s, x, y, size, col)
    Render.Text(font, size, s, Vec2(x + 1, y + 1), Color(0, 0, 0, 200))
    Render.Text(font, size, s, Vec2(x, y), col)
end

function script.OnDraw()
    if not ui.on or not ui.on:Get() or not hero then return end
    if not font then font = Render.LoadFont("Tahoma", Enum.FontCreate.FONTFLAG_ANTIALIAS, 500) end

    if ui.hud:Get() then
        text(string.format("Шагомер: %s · %d шагов", km(game.walked), steps(game.walked)), 20, 120, 14, Color(170, 235, 170, 230))
    end

    if summary and os.clock() < summary.till then
        local y = Render.ScreenSize().y * 0.3
        for i, l in ipairs(summary.lines) do
            local size = i == 1 and 18 or 15
            local w = Render.TextSize(font, size, l).x
            text(l, (Render.ScreenSize().x - w) / 2, y, size, Color(235, 245, 235, 240))
            y = y + size + 8
        end
    end
end

return script


