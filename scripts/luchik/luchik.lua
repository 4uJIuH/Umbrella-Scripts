-- утилиты

local function pick(list) return list[math.random(#list)] end

local function play(path)
    if not ui.sound:Get() then return end
    if type(path) == "table" then path = pick(path) end
    pcall(Engine.PlayVol, "sounds/" .. path .. ".vsnd_c", ui.volume:Get() / 100)
end

local lastChat = -100

local function tell(text, force)
    if not ui.chat:Get() or not text then return end
    if not force and os.clock() - lastChat < CHAT_GAP then return end
    lastChat = os.clock()
    pcall(Chat.Say, ALLIES, text)
end

-- миникарта

local mapQueue = {}
local mapNext = 0

local function ring(out, c, r, from, to, n)
    for i = 0, n do
        local a = math.rad(from + (to - from) * i / n)
        out[#out + 1] = { c.x + math.cos(a) * r, c.y + math.sin(a) * r, i == 0 }
    end
end

local function drawOnMap(center, evil)
    if not ui.map:Get() then return end
    local pts, r = {}, MAP_RADIUS
    ring(pts, center, r, 0, 360, 16)
    local ey, ex = center.y + r * 0.3, r * 0.35
    if evil then
        for _, sx in ipairs({ -1, 1 }) do
            local x = center.x + sx * ex
            pts[#pts + 1] = { x - r * 0.12, ey - r * 0.12, true }
            pts[#pts + 1] = { x + r * 0.12, ey + r * 0.12, false }
            pts[#pts + 1] = { x - r * 0.12, ey + r * 0.12, true }
            pts[#pts + 1] = { x + r * 0.12, ey - r * 0.12, false }
        end
        for i = 0, 6 do
            pts[#pts + 1] = { center.x - r * 0.55 + i * r * 0.18, center.y - r * 0.35 + ((i % 2 == 0) and 0 or -r * 0.18), i == 0 }
        end
    else
        for _, sx in ipairs({ -1, 1 }) do
            ring(pts, { x = center.x + sx * ex, y = ey }, r * 0.09, 0, 360, 6)
        end
        ring(pts, center, r * 0.6, 200, 340, 8)
    end
    for _, p in ipairs(pts) do mapQueue[#mapQueue + 1] = p end
end

local function drainMap(now)
    if not mapQueue[1] or now < mapNext then return end
    local p = table.remove(mapQueue, 1)
    pcall(MiniMap.SendLine, p[1], p[2], p[3], false)
    mapNext = now + MAP_STEP
end

-- логика

local hero = nil
local anger = 0
local stage = 0
local lastTalk = -100
local lastTip = -100
local say = nil
local scareUntil = 0
local lastTick = nil
local wasLow = false

local function speak(text, sound)
    say = { text = text, till = os.clock() + SAY_TIME }
    if sound then play(sound) end
end

local function stageOf(v)
    if v >= STAGE_CREEPY then return 2 end
    if v >= STAGE_CLINGY then return 1 end
    return 0
end

local function scare(now)
    anger = AFTER_SCARE
    stage = stageOf(anger)
    if ui.scare:Get() then
        scareUntil = now + SCARE_TIME
        play(SND.scream)
    end
    play(SND.laugh)
    tell(CHAT.scare, true)
    if hero then drawOnMap(Entity.GetAbsOrigin(hero), true) end
    say = { text = pick(LINES.sorry), till = now + SCARE_TIME + SAY_TIME }
end

local function setStage(s, now)
    if s == stage then return end
    local up = s > stage
    stage = s
    if not up then return end
    if s == 1 then
        speak(pick(LINES.clingy), SND.glitch)
        tell(CHAT.clingy)
    elseif s == 2 then
        speak(pick(LINES.creepy), SND.laugh)
        tell(CHAT.creepy, true)
        if hero then drawOnMap(Entity.GetAbsOrigin(hero), true) end
    end
end

local function alliesNear(me, pos)
    local n = 0
    for _, h in ipairs(Heroes.GetAll()) do
        if h ~= me and Entity.GetTeamNum(h) == Entity.GetTeamNum(me) and Entity.IsAlive(h) and not NPC.IsIllusion(h)
            and (Entity.GetAbsOrigin(h) - pos):Length2D() < NEAR_ALLY then
            n = n + 1
        end
    end
    return n
end

local function missingEnemies(me)
    local n = 0
    for _, h in ipairs(Heroes.GetAll()) do
        if Entity.GetTeamNum(h) ~= Entity.GetTeamNum(me) and Entity.IsAlive(h) and not NPC.IsIllusion(h) and Entity.IsDormant(h) then
            n = n + 1
        end
    end
    return n
end

function script.OnEntityKilled(data)
    if not hero or type(data) ~= "table" then return end
    if data.target == hero then
        anger = math.min(100, anger + DEATH_HURT)
        speak(pick(LINES.death), SND.glitch)
    elseif data.source == hero and data.target and Entity.IsHero(data.target) then
        anger = math.max(0, anger - KILL_MEND)
        speak(pick(LINES.kill), SND.talk)
    end
end

function script.OnUpdate()
    if not ui.on or not ui.on:Get() or not Engine.IsInGame() then return end
    local me = Heroes.GetLocal()
    if not me then return end
    local now = os.clock()

    if me ~= hero then
        hero, anger, stage, lastTalk = me, 0, 0, now
        speak(pick(LINES.hello), SND.talk)
        tell(CHAT.hello, true)
        drawOnMap(Entity.GetAbsOrigin(me), false)
    end

    local dt = lastTick and math.min(0.5, now - lastTick) or 0
    lastTick = now
    drainMap(now)
    if now < scareUntil then return end

    local pos = Entity.GetAbsOrigin(me)
    local near = Entity.IsAlive(me) and alliesNear(me, pos) or 0
    local grow = GROW_BASE + near * GROW_ALLY
    if now - lastTalk > IGNORED_AFTER then grow = grow + GROW_IGNORED end
    anger = math.min(100, anger + grow * dt)

    if ui.talk:IsPressed() and now - lastTalk > TALK_CD then
        lastTalk = now
        anger = math.max(0, anger - TALK_MEND)
        speak(pick(LINES.talk[stage + 1]), stage == 2 and SND.glitch or SND.talk)
        if stage == 0 then drawOnMap(pos, false) end
    end

    if anger >= 100 then
        scare(now)
        return
    end
    setStage(stageOf(anger), now)

    if say and now < say.till then return end
    if now - lastTip < TIP_GAP then return end

    local low = Entity.IsAlive(me) and Entity.GetHealth(me) < Entity.GetMaxHealth(me) * 0.3
    if low and not wasLow then
        lastTip = now
        speak(pick(LINES.lowhp))
    elseif near > 0 and stage >= 1 then
        lastTip = now
        speak(pick(LINES.jealous), SND.glitch)
    elseif stage == 0 and missingEnemies(me) >= 3 then
        lastTip = now
        speak(pick(LINES.missing))
    elseif math.random() < 0.3 then
        lastTip = now
        speak(pick(stage == 0 and LINES.friend or stage == 1 and LINES.clingy or LINES.creepy))
        if stage == 2 then play(SND.laugh) end
    end
    wasLow = low
end

-- рисуем

local font = nil

local function col(r, g, b, a) return Color(math.floor(r), math.floor(g), math.floor(b), math.floor(a or 255)) end

local function arc(c, r, from, to, color, thick)
    local pts = {}
    for i = 0, 16 do
        local a = math.rad(from + (to - from) * i / 16)
        pts[#pts + 1] = Vec2(c.x + math.cos(a) * r, c.y + math.sin(a) * r)
    end
    Render.PolyLine(pts, color, thick)
end

local function face(c, r, mood, t)
    local yellow = mood == 2 and col(215, 180, 40) or col(255, 214, 40)
    local ink = col(30, 20, 10)
    local light = ({ col(90, 230, 90), col(255, 160, 40), col(255, 40, 40) })[mood + 1]

    Render.Line(Vec2(c.x, c.y - r), Vec2(c.x + r * 0.15, c.y - r * 1.45), ink, math.max(2, r * 0.05))
    if mood < 2 or math.floor(t * 6) % 2 == 0 then
        Render.FilledCircle(Vec2(c.x + r * 0.15, c.y - r * 1.5), r * 0.1, light)
    end

    Render.FilledCircle(c, r, yellow)
    Render.Circle(c, r, col(180, 130, 20), math.max(2, r * 0.05))

    local ex, ey = r * 0.36, c.y - r * 0.18
    if mood == 0 then
        Render.FilledCircle(Vec2(c.x - r * 0.55, c.y + r * 0.15), r * 0.14, col(255, 140, 140, 150))
        Render.FilledCircle(Vec2(c.x + r * 0.55, c.y + r * 0.15), r * 0.14, col(255, 140, 140, 150))
        for _, sx in ipairs({ -1, 1 }) do
            local blink = (math.floor(t * 10) % 40 == 0) and 0.02 or 0.15
            Render.FilledRect(Vec2(c.x + sx * ex - r * 0.08, ey - r * blink), Vec2(c.x + sx * ex + r * 0.08, ey + r * blink), ink, r * 0.08)
        end
        arc(c, r * 0.55, 20, 160, ink, math.max(2, r * 0.07))
    elseif mood == 1 then
        for _, sx in ipairs({ -1, 1 }) do
            Render.FilledRect(Vec2(c.x + sx * ex - r * 0.12, ey - r * 0.03), Vec2(c.x + sx * ex + r * 0.12, ey + r * 0.06), ink)
        end
        Render.Line(Vec2(c.x - r * 0.35, c.y + r * 0.4), Vec2(c.x + r * 0.35, c.y + r * 0.4), ink, math.max(2, r * 0.07))
        Render.Line(Vec2(c.x + r * 0.35, c.y + r * 0.4), Vec2(c.x + r * 0.45, c.y + r * 0.32), ink, math.max(2, r * 0.07))
    else
        for _, sx in ipairs({ -1, 1 }) do
            local e = Vec2(c.x + sx * ex, ey)
            Render.FilledCircle(e, r * 0.18, ink)
            Render.FilledCircle(e, r * 0.04, col(255, 30, 30))
        end
        local zig = {}
        for i = 0, 8 do
            zig[#zig + 1] = Vec2(c.x - r * 0.5 + i * r * 0.125, c.y + r * 0.42 + ((i % 2 == 0) and 0 or -r * 0.12))
        end
        Render.PolyLine(zig, ink, math.max(2, r * 0.06))
        Render.PolyLine({ Vec2(c.x - r * 0.1, c.y - r * 0.95), Vec2(c.x + r * 0.05, c.y - r * 0.6), Vec2(c.x - r * 0.08, c.y - r * 0.35), Vec2(c.x + r * 0.1, c.y - r * 0.1) }, ink, math.max(1, r * 0.03))
    end
end

local function scareFace(t)
    local s = Render.ScreenSize()
    Render.FilledRect(Vec2(0, 0), Vec2(s.x, s.y), col(40, 0, 0, 235))
    local c = Vec2(s.x / 2 + math.random(-12, 12), s.y / 2 + math.random(-12, 12))
    local r = s.y * 0.42
    Render.FilledCircle(c, r, col(200, 165, 30))
    for _, sx in ipairs({ -1, 1 }) do
        local e = Vec2(c.x + sx * r * 0.38, c.y - r * 0.22)
        Render.FilledCircle(e, r * 0.2, col(0, 0, 0))
        for k = 1, 4 do Render.Circle(e, r * 0.04 * k, col(255, 20, 20), 3) end
    end
    Render.FilledRect(Vec2(c.x - r * 0.6, c.y + r * 0.15), Vec2(c.x + r * 0.6, c.y + r * 0.6), col(10, 0, 0), r * 0.1)
    for i = 0, 9 do
        local x = c.x - r * 0.55 + i * r * 0.11
        Render.FilledRect(Vec2(x, c.y + r * 0.15), Vec2(x + r * 0.07, c.y + r * 0.27), col(240, 235, 210))
        Render.FilledRect(Vec2(x + r * 0.03, c.y + r * 0.48), Vec2(x + r * 0.1, c.y + r * 0.6), col(240, 235, 210))
    end
    for _ = 1, 6 do
        local y = math.random(0, math.floor(s.y))
        Render.FilledRect(Vec2(0, y), Vec2(s.x, y + math.random(2, 14)), col(255, 255, 255, math.random(20, 90)))
    end
end

local function bubble(c, r, text)
    local size = 15
    local w = Render.TextSize(font, size, text)
    local x, y = c.x - w.x / 2, c.y - r * 1.75 - w.y - 16
    Render.FilledRect(Vec2(x - 10, y - 6), Vec2(x + w.x + 10, y + w.y + 6), col(255, 250, 225, 235), 8)
    Render.Text(font, size, text, Vec2(x, y), col(40, 30, 10))
end

function script.OnDraw()
    if not ui.on or not ui.on:Get() or not hero then return end
    if not font then font = Render.LoadFont("Tahoma", Enum.FontCreate.FONTFLAG_ANTIALIAS, 600) end
    local now = os.clock()

    if now < scareUntil then
        scareFace(now)
        return
    end

    local p, visible = Render.WorldToScreen(Entity.GetAbsOrigin(hero) + Vector(0, 0, HEIGHT))
    if not visible then return end
    local r = ui.size:Get()
    local jitter = stage == 2 and math.random(-2, 2) or 0
    local c = Vec2(p.x + jitter, p.y + math.sin(now * 2) * r * 0.12)
    face(c, r, stage, now)

    if say and now < say.till then bubble(c, r, say.text) end

    if ui.show:Get() then
        local w = r * 2
        Render.FilledRect(Vec2(c.x - w / 2, c.y + r + 10), Vec2(c.x + w / 2, c.y + r + 16), col(0, 0, 0, 160))
        Render.FilledRect(Vec2(c.x - w / 2, c.y + r + 10), Vec2(c.x - w / 2 + w * anger / 100, c.y + r + 16), col(230, 60 + (100 - anger) * 1.5, 40))
    end

    if stage == 2 then
        local s = Render.ScreenSize()
        Render.Gradient(Vec2(0, 0), Vec2(s.x, s.y * 0.15), col(0, 0, 0, 120), col(0, 0, 0, 120), col(0, 0, 0, 0), col(0, 0, 0, 0))
        Render.Gradient(Vec2(0, s.y * 0.85), Vec2(s.x, s.y), col(0, 0, 0, 0), col(0, 0, 0, 0), col(0, 0, 0, 120), col(0, 0, 0, 120))
    end
end

return script


